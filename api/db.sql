-- Santillana — schema MySQL (utf8mb4). Precios en CENTAVOS (int), nunca float.
CREATE DATABASE IF NOT EXISTS santillana CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE santillana;

CREATE TABLE IF NOT EXISTS products (
  id VARCHAR(32) PRIMARY KEY,
  sku VARCHAR(32) NOT NULL UNIQUE,
  nombre VARCHAR(255) NOT NULL,
  slug VARCHAR(255) NOT NULL UNIQUE,
  marca VARCHAR(80) NOT NULL DEFAULT '',
  cat_primary VARCHAR(40) NOT NULL DEFAULT '',
  precio INT NOT NULL DEFAULT 0,
  precio_lista INT NOT NULL DEFAULT 0,
  moneda CHAR(3) NOT NULL DEFAULT 'MXN',
  stock INT NOT NULL DEFAULT 0,
  reservado INT NOT NULL DEFAULT 0,
  disponible TINYINT(1) NOT NULL DEFAULT 1,
  destacado TINYINT(1) NOT NULL DEFAULT 0,
  en_oferta TINYINT(1) NOT NULL DEFAULT 0,
  img VARCHAR(255) NOT NULL DEFAULT '',
  img_large VARCHAR(255) NOT NULL DEFAULT '',
  img_webp VARCHAR(255) NOT NULL DEFAULT '',
  img_large_webp VARCHAR(255) NOT NULL DEFAULT '',
  descripcion_corta VARCHAR(500) NOT NULL DEFAULT '',
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_cat (cat_primary), KEY idx_disp (disponible)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS product_cats (
  product_id VARCHAR(32) NOT NULL,
  cat VARCHAR(40) NOT NULL,
  PRIMARY KEY (product_id, cat),
  CONSTRAINT fk_pc_prod FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS orders (
  id INT AUTO_INCREMENT PRIMARY KEY,
  folio VARCHAR(16) NOT NULL UNIQUE,
  idempotency_key CHAR(36) NOT NULL UNIQUE,
  email VARCHAR(160) NOT NULL, nombre VARCHAR(160) NOT NULL,
  apellidos VARCHAR(160) NOT NULL DEFAULT '',
  telefono VARCHAR(20) NOT NULL, direccion VARCHAR(220) NOT NULL,
  depto VARCHAR(120) NOT NULL DEFAULT '',
  ciudad VARCHAR(120) NOT NULL, estado VARCHAR(80) NOT NULL DEFAULT '',
  pais VARCHAR(60) NOT NULL DEFAULT 'México', cp CHAR(5) NOT NULL,
  billing_same TINYINT(1) NOT NULL DEFAULT 1,
  billing_address VARCHAR(300) NOT NULL DEFAULT '',
  subscribe_news TINYINT(1) NOT NULL DEFAULT 0,
  payment_method VARCHAR(10) NOT NULL DEFAULT 'paypal',
  subtotal INT NOT NULL, envio INT NOT NULL, total INT NOT NULL,
  currency CHAR(3) NOT NULL DEFAULT 'MXN',
  status ENUM('PENDING','PENDING_TRANSFER','PAID','CANCELLED','REFUNDED','EXPIRED') NOT NULL DEFAULT 'PENDING',
  paypal_order_id VARCHAR(64) DEFAULT NULL UNIQUE,
  paypal_capture_id VARCHAR(64) DEFAULT NULL,
  spei_ref VARCHAR(64) DEFAULT NULL,
  customer_id INT DEFAULT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  paid_at TIMESTAMP NULL DEFAULT NULL,
  KEY idx_status (status), KEY idx_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS order_items (
  order_id INT NOT NULL,
  product_id VARCHAR(32) NOT NULL,
  qty INT NOT NULL,
  unit_price INT NOT NULL,
  PRIMARY KEY (order_id, product_id),
  CONSTRAINT fk_oi_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS webhook_log (
  id INT AUTO_INCREMENT PRIMARY KEY,
  source VARCHAR(20) NOT NULL DEFAULT 'paypal',
  event_type VARCHAR(80) NOT NULL DEFAULT '',
  payload MEDIUMTEXT NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS customers (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(160) NOT NULL,
  email VARCHAR(160) NOT NULL UNIQUE,
  pass_hash VARCHAR(255) NOT NULL,
  telefono VARCHAR(20) NOT NULL DEFAULT '',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  KEY idx_cemail (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS customer_carts (
  customer_id INT NOT NULL,
  product_id VARCHAR(32) NOT NULL,
  qty INT NOT NULL DEFAULT 1,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (customer_id, product_id),
  CONSTRAINT fk_cc_cust FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS newsletter (
  id INT AUTO_INCREMENT PRIMARY KEY, email VARCHAR(160) NOT NULL UNIQUE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS mensajes (
  id INT AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(160) NOT NULL, email VARCHAR(160) NOT NULL,
  mensaje VARCHAR(2000) NOT NULL, leido TINYINT(1) NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS accesos (
  id INT AUTO_INCREMENT PRIMARY KEY,
  tipo ENUM('admin','cliente') NOT NULL,
  email VARCHAR(160) NOT NULL,
  ip VARCHAR(45) NOT NULL DEFAULT '',
  agente VARCHAR(255) NOT NULL DEFAULT '',
  entrada TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  salida TIMESTAMP NULL DEFAULT NULL,
  segundos INT DEFAULT NULL,
  KEY idx_tipo (tipo), KEY idx_email (email), KEY idx_entrada (entrada)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
